<#
.SYNOPSIS
  Builds the AgentUsageMonitor Windows x64 release candidate: release
  binaries, a portable ZIP and (when Inno Setup 6 is available) the per-user
  installer. Nothing is installed, uninstalled or published.

.EXAMPLE
  pwsh -File packaging\windows\build-installer.ps1
  pwsh -File packaging\windows\build-installer.ps1 -SkipBuild
  pwsh -File packaging\windows\build-installer.ps1 -OutputDirectory C:\temp\aum-out -TargetDirectory C:\temp\aum-target

.NOTES
  Requires: Rust stable with the x86_64-pc-windows-msvc target and the MSVC
  build tools (the same as a normal `cargo build`).
  Installer step requires Inno Setup 6 (ISCC.exe). Install it once with:
    winget install --id JRSoftware.InnoSetup -e
  or from https://jrsoftware.org/isdl.php. If ISCC.exe is missing, the script
  still produces the portable ZIP, prints this hint and exits with code 2.
#>
[CmdletBinding()]
param(
    [switch]$SkipBuild,
    [string]$Iscc,
    # Isolate installer, portable ZIP, and staging files from existing outputs.
    [string]$OutputDirectory,
    # Isolate the Cargo build so existing release EXEs are never replaced.
    [string]$TargetDirectory,
    # Build even if the provider marks to embed are missing (the app then
    # shows only marks from the user's local provider-icons folder).
    [switch]$AllowMissingProviderIcons
)
$ErrorActionPreference = 'Stop'

$repo = Resolve-Path (Join-Path $PSScriptRoot '..\..')
$rust = Join-Path $repo 'rust'
$out = if ($OutputDirectory) { [IO.Path]::GetFullPath($OutputDirectory) } else { Join-Path $rust 'target\installer' }
$target = if ($TargetDirectory) { [IO.Path]::GetFullPath($TargetDirectory) } else { Join-Path $rust 'target' }
$stage = Join-Path $out 'stage'

$versionLine = Select-String -Path (Join-Path $rust 'agent-monitor-ui\Cargo.toml') -Pattern '^version\s*=\s*"([^"]+)"' | Select-Object -First 1
if (-not $versionLine) { throw 'Could not read the version from agent-monitor-ui/Cargo.toml' }
$version = $versionLine.Matches[0].Groups[1].Value
Write-Host "AgentUsageMonitor $version (x86_64-pc-windows-msvc)"

$zip = Join-Path $out "AgentUsageMonitor-$version-win-x64-portable.zip"
$setup = Join-Path $out "AgentUsageMonitor-$version-win-x64-setup.exe"
foreach ($path in @($stage, $zip, $setup)) {
    if (Test-Path $path) { throw "Refusing to overwrite existing build output: $path" }
}
if (Test-Path $out) {
    if (Get-ChildItem -LiteralPath $out -Force | Select-Object -First 1) {
        throw "Output directory is not empty; choose a new directory: $out"
    }
} else {
    New-Item -ItemType Directory -Force -Path $out | Out-Null
}

# The tracked original SVGs are embedded automatically by build.rs. Keep the
# optional bypass for maintainers intentionally building an unbranded variant.
$providerDir = Join-Path $rust 'agent-monitor-ui\assets\providers'
$providerAssets = @(
    'OAI_OpenAI-Blossom_White.svg',
    'OAI_OpenAI-Blossom_Black.svg',
    'Claude Spark - Clay.svg'
)
$missing = @($providerAssets | Where-Object { -not (Test-Path (Join-Path $providerDir $_)) })
if ($missing) {
    $message = "Tracked provider SVGs are missing: $($missing -join ', ') (folder: $providerDir)"
    if ($AllowMissingProviderIcons) { Write-Warning $message } else { throw "$message. Use -AllowMissingProviderIcons to build without them." }
} else {
    Write-Host "Tracked provider SVGs: all three present in $providerDir"
}

if (-not $SkipBuild) {
    Push-Location $rust
    $previousTargetDirectory = $env:CARGO_TARGET_DIR
    try {
        $env:CARGO_TARGET_DIR = $target
        cargo build --release --target x86_64-pc-windows-msvc -p agent-usage-monitor-ui -p agent-usage-monitor-core --bins
        if ($LASTEXITCODE -ne 0) { throw "cargo build failed ($LASTEXITCODE)" }
    } finally {
        $env:CARGO_TARGET_DIR = $previousTargetDirectory
        Pop-Location
    }
}

$release = Join-Path $target 'x86_64-pc-windows-msvc\release'
$appExe = Join-Path $release 'agent-usage-monitor.exe'
$bridgeExe = Join-Path $release 'agent-usage-monitor-claude-bridge.exe'
foreach ($file in $appExe, $bridgeExe) {
    if (-not (Test-Path $file)) { throw "Missing release binary: $file" }
}
# Static AUM icon generated by build.rs (the same frames embedded in the EXE).
$icon = Get-ChildItem (Join-Path $release 'build') -Recurse -Filter 'aum-app.ico' -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending | Select-Object -First 1
if (-not $icon) { throw 'aum-app.ico not found in the release build output' }

New-Item -ItemType Directory -Force $stage | Out-Null
Copy-Item $appExe, $bridgeExe $stage
Copy-Item (Join-Path $repo 'LICENSE'), (Join-Path $repo 'README.md') $stage
Copy-Item $icon.FullName (Join-Path $stage 'aum.ico')

# Guard: provider marks live only inside the EXE; no loose third-party
# artwork files may be staged into the ZIP or installer.
$forbidden = Get-ChildItem $stage -Recurse -File | Where-Object {
    $_.Extension -in '.png', '.svg' -or $_.Name -match '(?i)codex|claude.*\.(png|svg|ico)|openai|blossom|spark'
}
if ($forbidden) { throw "Provider artwork found in the staging folder: $($forbidden.Name -join ', ')" }

Compress-Archive -Path (Join-Path $stage '*.exe'), (Join-Path $stage 'LICENSE'), (Join-Path $stage 'README.md') -DestinationPath $zip
Write-Host "Portable ZIP: $zip"

if (-not $Iscc) {
    $candidates = @(
        (Get-Command 'ISCC.exe' -ErrorAction SilentlyContinue).Source,
        (Join-Path ${env:ProgramFiles(x86)} 'Inno Setup 6\ISCC.exe'),
        (Join-Path $env:ProgramFiles 'Inno Setup 6\ISCC.exe'),
        (Join-Path $env:LOCALAPPDATA 'Programs\Inno Setup 6\ISCC.exe')
    ) | Where-Object { $_ -and (Test-Path $_) }
    $Iscc = $candidates | Select-Object -First 1
}
if ($Iscc -and -not (Test-Path $Iscc)) { throw "Inno Setup compiler not found: $Iscc" }
$artifacts = @($zip)
if (-not $Iscc) {
    Write-Warning 'Inno Setup 6 (ISCC.exe) was not found; the installer was not built.'
    Write-Warning 'Install it once with: winget install --id JRSoftware.InnoSetup -e'
    Write-Warning 'Then run this script again (use -SkipBuild to reuse the binaries).'
} else {
    & $Iscc "/DAppVersion=$version" "/DStageDir=$stage" "/DOutputDir=$out" (Join-Path $PSScriptRoot 'AgentUsageMonitor.iss')
    if ($LASTEXITCODE -ne 0) { throw "ISCC failed ($LASTEXITCODE)" }
    $artifacts += $setup
}

foreach ($artifact in $artifacts) {
    $hash = (Get-FileHash $artifact -Algorithm SHA256).Hash
    Write-Host ("{0}  {1}  ({2:N0} bytes)" -f $hash, (Split-Path $artifact -Leaf), (Get-Item $artifact).Length)
}
if (-not $Iscc) { exit 2 }
